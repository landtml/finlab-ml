"""Tests for tools/check_attribution.py (AI attribution guard for commits and PR bodies)."""

from __future__ import annotations

import importlib.util
import os
import subprocess
import sys
from pathlib import Path

TOOL = Path(__file__).resolve().parent.parent / "tools" / "check_attribution.py"

_spec = importlib.util.spec_from_file_location("check_attribution", TOOL)
check_attribution = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(check_attribution)
find_violations = check_attribution.find_violations


def test_co_authored_by_ai_line_is_flagged():
    text = "Fix parser\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n"
    violations = find_violations(text)
    assert violations == ["Co-Authored-By: Claude <noreply@anthropic.com>"]


def test_co_authored_by_person_is_not_flagged():
    text = "Fix parser\n\nCo-Authored-By: Jane Doe <jane@example.com>\n"
    assert find_violations(text) == []


def test_claude_session_line_is_flagged():
    text = "Tidy docs\n\nClaude-Session: session_01XyZ\n"
    assert find_violations(text) == ["Claude-Session: session_01XyZ"]


def test_generated_by_footer_is_flagged():
    text = "Add plot\n\n_Generated by [Claude Code](https://claude.com/claude-code)_\n"
    assert find_violations(text) == [
        "_Generated by [Claude Code](https://claude.com/claude-code)_"
    ]


def test_session_link_is_flagged():
    text = "Notes\n\nSee https://claude.ai/code/session_01AbC for context.\n"
    assert find_violations(text) == [
        "See https://claude.ai/code/session_01AbC for context."
    ]


def test_attribution_marker_and_requested_by_project_link_are_not_flagged():
    text = (
        "<!-- claude-projects-attribution -->\n"
        "_Requested by Frederik in https://claude.ai/code/project/abc123_\n"
    )
    assert find_violations(text) == []


def test_clean_message_passes():
    text = "Add stationarity test\n\nCovers the ADF path and the edge case of empty input.\n"
    assert find_violations(text) == []


def test_claude_code_outside_footer_is_not_flagged():
    text = "Document how to use Claude Code with the CLI tools.\n"
    assert find_violations(text) == []


def test_cli_body_file_exit_codes(tmp_path):
    bad = tmp_path / "bad.md"
    bad.write_text("Summary\n\nClaude-Session: session_01XyZ\n", encoding="utf-8")
    good = tmp_path / "good.md"
    good.write_text("Summary\n\nPlain description.\n", encoding="utf-8")

    r_bad = subprocess.run(
        [sys.executable, str(TOOL), "--body-file", str(bad)],
        capture_output=True, text=True,
    )
    r_good = subprocess.run(
        [sys.executable, str(TOOL), "--body-file", str(good)],
        capture_output=True, text=True,
    )
    assert r_bad.returncode == 1
    assert "Claude-Session: session_01XyZ" in r_bad.stdout
    assert r_good.returncode == 0


def test_cli_commits_range_reads_git_log(tmp_path):
    env = dict(os.environ)
    env.update(
        GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@example.com",
        GIT_COMMITTER_NAME="t", GIT_COMMITTER_EMAIL="t@example.com",
    )
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    (tmp_path / "f.txt").write_text("x", encoding="utf-8")
    subprocess.run(["git", "-C", str(tmp_path), "add", "f.txt"], check=True)
    subprocess.run(
        ["git", "-C", str(tmp_path), "commit", "-q", "-m", "Add f",
         "-m", "Claude-Session: session_01XyZ"],
        check=True, env=env,
    )
    r = subprocess.run(
        [sys.executable, str(TOOL), "--commits", "HEAD"],
        capture_output=True, text=True, cwd=tmp_path, env=env,
    )
    assert r.returncode == 1
    assert "Claude-Session: session_01XyZ" in r.stdout
