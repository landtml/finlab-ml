"""Generate docs/API.md from the public names and signatures of each module.

Run from the repository root:  PYTHONPATH=src python3 tools/gen_api.py
"""
from __future__ import annotations

import importlib
import inspect
from pathlib import Path

MODULES = [
    ("quantowl.cv", "Cross-validation (AFML ch. 7)"),
    ("quantowl.bars", "Financial data structures (AFML ch. 2)"),
    ("quantowl.labeling", "Labeling (AFML ch. 3)"),
    ("quantowl.weights", "Sample weights (AFML ch. 4)"),
    ("quantowl.monte_carlo", "Monte Carlo experiments (AFML ch. 4)"),
    ("quantowl.fracdiff", "Fractionally differentiated features (AFML ch. 5)"),
    ("quantowl.ensemble", "Ensemble methods (AFML ch. 6)"),
    ("quantowl.importance", "Feature importance (AFML ch. 8)"),
    ("quantowl.tuning", "Hyper-parameter tuning (AFML ch. 9)"),
    ("quantowl.bet_sizing", "Bet sizing (AFML ch. 10)"),
    ("quantowl.pbo", "Backtest overfitting via CSCV (AFML ch. 11)"),
    ("quantowl.trading_rules", "Optimal trading rules on an Ornstein-Uhlenbeck process (AFML ch. 13)"),
    ("quantowl.stats", "Backtest statistics (AFML ch. 14)"),
    ("quantowl.strategy_risk", "Strategy risk (AFML ch. 15)"),
    ("quantowl.trials", "Trial records that feed PBO and deflated Sharpe (not AFML; feeds ch. 11 and 14)"),
    ("quantowl.onc", "ONC correlation clustering (not AFML)"),
    ("quantowl.plot", "Plotly figures for PBO, deflated Sharpe and the Monte Carlo experiment (optional extra)"),
    ("quantowl.hrp", "Hierarchical risk parity (AFML ch. 16)"),
    ("quantowl.structural_breaks", "Structural breaks (AFML ch. 17)"),
    ("quantowl.entropy", "Entropy features (AFML ch. 18)"),
    ("quantowl.microstructure", "Microstructure features (AFML ch. 19)"),
    ("quantowl.parallel", "Multiprocessing helpers (AFML ch. 20)"),
    ("quantowl.agent.tools", "Agent tool registry (MCP server, see docs/AGENTS.md)"),
]


def _first_line(doc: str | None) -> str:
    if not doc:
        return ""
    return inspect.cleandoc(doc).splitlines()[0]


def main() -> None:
    out = [
        "# quantowl API reference",
        "",
        "Generated by `tools/gen_api.py` from each module's `__all__`, signatures and",
        "docstrings. Do not edit by hand; rerun the generator instead.",
        "",
    ]
    for mod_name, title in MODULES:
        mod = importlib.import_module(mod_name)
        names = getattr(mod, "__all__", [])
        out += [f"## `{mod_name}`", "", title, ""]
        for name in names:
            obj = getattr(mod, name)
            if inspect.isclass(obj):
                try:
                    sig = str(inspect.signature(obj))
                except (TypeError, ValueError):
                    sig = "(...)"
                kind = "class"
            elif callable(obj):
                try:
                    sig = str(inspect.signature(obj))
                except (TypeError, ValueError):
                    sig = "(...)"
                kind = "function"
            else:
                sig, kind = "", "constant"
            summary = _first_line(getattr(obj, "__doc__", ""))
            out.append(f"- **`{name}{sig if kind != 'constant' else ''}`** ({kind}). {summary}")
        out.append("")
    path = Path(__file__).resolve().parents[1] / "docs" / "API.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
